-- ---------------------------------------------------------------------------
-- Public clinic directory (SEO clinic and suburb pages)
--
-- Backs the unauthenticated GET /api/public/clinics and
-- GET /api/public/clinics/{slug} endpoints served by clinic-service. Only
-- clinics that are approved, enabled AND opted in (listed_publicly) are ever
-- returned; existing clinics default to NOT listed because they never agreed
-- to public listing.
-- ---------------------------------------------------------------------------

-- Opt-in, stable URL slug and map location. The slug is assigned by
-- clinic-service once a clinic is approved; a rename moves the old value to
-- clinic_slug_history so the frontend can 301-redirect old URLs.
alter table clinics add column slug varchar(160);
alter table clinics add column listed_publicly boolean default false not null;
alter table clinics add column latitude double precision;
alter table clinics add column longitude double precision;
alter table clinics add constraint uk_clinics_slug unique (slug);
alter table clinics add constraint ck_clinics_slug_format
    check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$');
alter table clinics add constraint ck_clinics_latitude
    check (latitude between -90 and 90);
alter table clinics add constraint ck_clinics_longitude
    check (longitude between -180 and 180);

-- The public clinic page shows the description, so it needs more than the
-- 255 characters the ddl-auto era gave it. varchar -> text is binary
-- compatible in PostgreSQL (no table rewrite) and both String mappings
-- (auth-service and clinic-service) keep validating.
alter table clinics alter column description type text;

-- Slugs a clinic used before a rename. A retired slug stays reserved for its
-- clinic forever (primary key across all clinics), so an old URL can never
-- start pointing at a different clinic.
create table clinic_slug_history (
    slug varchar(160) not null,
    clinic_id bigint not null,
    retired_at timestamp(6) not null,
    primary key (slug),
    constraint fk_clinic_slug_history_clinic foreign key (clinic_id)
        references clinics (id) on delete cascade,
    constraint ck_clinic_slug_history_format
        check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);
create index idx_clinic_slug_history_clinic_id on clinic_slug_history (clinic_id);

-- Weekly opening hours, one row per day. day_of_week is 0 (Sunday) to
-- 6 (Saturday), matching OperatingHours in the frontend's src/types/api.ts.
-- Closed days keep their times (the frontend type has non-nullable times).
create table clinic_operating_hours (
    id bigint generated by default as identity,
    clinic_id bigint not null,
    day_of_week integer not null,
    open_time time(6) not null,
    close_time time(6) not null,
    is_open boolean not null,
    primary key (id),
    constraint uk_clinic_operating_hours_day unique (clinic_id, day_of_week),
    constraint fk_clinic_operating_hours_clinic foreign key (clinic_id)
        references clinics (id) on delete cascade,
    constraint ck_clinic_operating_hours_day check (day_of_week between 0 and 6),
    constraint ck_clinic_operating_hours_range check (not is_open or open_time < close_time)
);

-- Single-row coordination state for the frontend rebuild trigger (Vercel
-- Deploy Hook). Every clinic-service replica locks this row with
-- FOR UPDATE SKIP LOCKED, so only one of them evaluates and calls the hook,
-- and the at-most-once-per-hour throttle survives restarts.
create table public_directory_sync (
    id integer not null,
    published_fingerprint varchar(64),
    last_hook_at timestamp(6),
    last_attempt_at timestamp(6),
    last_error varchar(255),
    primary key (id),
    constraint ck_public_directory_sync_singleton check (id = 1)
);
insert into public_directory_sync (id) values (1);

-- DATA-02 authoring rule: new tables default to no service access. Deletes
-- of a clinic by auth-service (rejected registration) cascade through the
-- foreign keys above; PostgreSQL runs referential actions as the table owner,
-- so svc_auth needs no grant on these tables.
grant select, insert, update, delete on clinic_slug_history, clinic_operating_hours,
    public_directory_sync to svc_clinic;
