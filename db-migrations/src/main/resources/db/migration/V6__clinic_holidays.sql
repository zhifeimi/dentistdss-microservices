-- ---------------------------------------------------------------------------
-- Clinic holidays and one-off closures
--
-- Backs /clinic/{clinicId}/holidays in clinic-service (the dashboard's
-- Holidays page). A recurring holiday repeats every year on the same month
-- and day; holiday_date keeps the first occurrence. A day that is not a full
-- closure carries its special opening hours.
-- ---------------------------------------------------------------------------
create table clinic_holidays (
    id bigint generated by default as identity,
    clinic_id bigint not null,
    name varchar(120) not null,
    holiday_date date not null,
    description varchar(500),
    type varchar(32) not null,
    is_full_day_closure boolean not null,
    special_opening_time time(6),
    special_closing_time time(6),
    is_recurring boolean not null,
    emergency_contact varchar(100),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_clinic_holidays_date unique (clinic_id, holiday_date),
    constraint fk_clinic_holidays_clinic foreign key (clinic_id)
        references clinics (id) on delete cascade,
    constraint ck_clinic_holidays_type check (type in ('NATIONAL_HOLIDAY',
        'CLINIC_CLOSURE', 'STAFF_TRAINING', 'MAINTENANCE', 'EMERGENCY_CLOSURE',
        'VACATION', 'OTHER')),
    constraint ck_clinic_holidays_special_hours check (is_full_day_closure
        or (special_opening_time is not null and special_closing_time is not null
            and special_opening_time < special_closing_time))
);

-- DATA-02: new tables default to no service access; only clinic-service
-- reads and writes holidays. Clinic deletes cascade as the table owner.
grant select, insert, update, delete on clinic_holidays to svc_clinic;
